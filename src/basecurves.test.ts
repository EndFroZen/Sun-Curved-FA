import { selectFrom, editCols } from "./basecurves.ts";
const C = (name: string, pk = false) => ({ name, type: "", pk });
const structs = new Map([["orders", [C("id", true), C("cust_id"), C("total")]], ["cust", [C("id", true), C("name")]]]);
const ec = (d: "mysql" | "postgres" | "sqlite", sql: string) => {
  const p = selectFrom(d, sql);
  return p && Object.fromEntries([...editCols(d, p, structs)].map(([n, s]) => [n, `${s.t}.${s.col.name} by ${s.keys.map(([k, r]) => `${k.name}<-${r}`).join()}`]));
};
assert.deepEqual(ec("mysql", "-- x\nSELECT * FROM `orders` o WHERE o.id > 1;"), { id: "orders.id by id<-id", cust_id: "orders.cust_id by id<-id", total: "orders.total by id<-id" });
// join: both tables have "id" → ambiguous under *, so only tables whose key is aliased/unique stay editable
assert.deepEqual(ec("postgres", "select o.id, o.total, c.id as cid, c.name, upper(c.name) as up from orders o left join cust c on c.id = o.cust_id"),
  { id: "orders.id by id<-id", total: "orders.total by id<-id", cid: "cust.id by id<-cid", name: "cust.name by id<-cid" });
assert.deepEqual(ec("sqlite", "select * from orders o join cust c on c.id = o.cust_id"), {}); // id twice, no key for either
assert.deepEqual(ec("sqlite", "select o.*, name from orders o, cust"), { id: "orders.id by id<-id", cust_id: "orders.cust_id by id<-id", total: "orders.total by id<-id" });
assert.deepEqual(ec("sqlite", "select total from orders"), {}); // no key in result
assert.deepEqual(ec("mysql", "select ID, Total from orders"), { ID: "orders.id by id<-ID", Total: "orders.total by id<-ID" });
assert.equal(selectFrom("sqlite", "select count(*) from a group by x"), null);
assert.equal(selectFrom("sqlite", "select (select 1 from b) from a"), null);
assert.equal(selectFrom("sqlite", "select * from a join (select 1) b on 1=1"), null);
assert.equal(selectFrom("postgres", "select * from public.t"), null);
assert.equal(selectFrom("sqlite", "update t set a=1"), null);
assert.deepEqual(selectFrom("postgres", 'select * from "Foo""x" f')?.tables, [{ name: 'Foo"x', alias: "f" }]);
console.log("editCols ok");

import { builderSql } from "./basecurves.ts";
const T = (a: string, t = a) => ({ a, t });
assert.equal(builderSql("postgres", { tables: [T("orders"), T("cust")], joins: [{ a: "orders", ac: "cust_id", b: "cust", bc: "id", type: "LEFT" }],
  cols: [{ a: "orders", c: "id" }, { a: "cust", c: "id" }, { a: "cust", c: "name" }], where: "where total > 5", limit: 100 }),
  'SELECT "orders"."id" AS "orders_id",\n  "cust"."id" AS "cust_id",\n  "cust"."name"\nFROM "orders"\nLEFT JOIN "cust" ON "orders"."cust_id" = "cust"."id"\nWHERE total > 5\nLIMIT 100');
// join written from the far side flips LEFT→RIGHT; a 2nd join between included tables ANDs; loose table cross joins; alias
assert.equal(builderSql("mysql", { tables: [T("a"), T("b"), T("c"), T("a_2", "a")],
  joins: [{ a: "b", ac: "x", b: "a", bc: "x", type: "LEFT" }, { a: "a", ac: "y", b: "b", bc: "y", type: "INNER" }], cols: [], where: "", limit: 0 }),
  "SELECT *\nFROM `a`\nRIGHT JOIN `b` ON `b`.`x` = `a`.`x` AND `a`.`y` = `b`.`y`\nCROSS JOIN `c`\nCROSS JOIN `a` AS `a_2`");
assert.equal(builderSql("sqlite", { tables: [], joins: [], cols: [], where: "", limit: 0 }), "");
// builder output stays editable (parser understands it)
const bs = builderSql("postgres", { tables: [T("orders"), T("cust")], joins: [{ a: "orders", ac: "cust_id", b: "cust", bc: "id", type: "LEFT" }], cols: [{ a: "orders", c: "id" }, { a: "orders", c: "total" }, { a: "cust", c: "name" }], where: "", limit: 10 });
assert.deepEqual(Object.keys(Object.fromEntries(editCols("postgres", selectFrom("postgres", bs)!, structs))), ["id", "total"]);
console.log("builder ok");

// filter boxes → WHERE; filters on tables outside the query are ignored
